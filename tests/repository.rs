//! Real Git inventories and provenance, exercised through the library seam.

use howmany::{AnalysisOptions, Engine};
use std::path::Path;
use std::process::Command;

fn git(root: &Path, args: &[&str]) {
    let output = Command::new("git")
        .arg("-C")
        .arg(root)
        .args(args)
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

fn write(root: &Path, path: &str, text: &str) {
    let path = root.join(path);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

#[test]
fn tracked_source_uses_working_bytes_and_nested_git_provenance() {
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path();
    git(root, &["init", "-q"]);
    for path in [
        "src/main.rs",
        "packages/ui/widget.ts",
        "ci/pipeline/build/source.go",
        "ci/workbench/coverage/source.py",
        ".hooks/hook.py",
        "ignored.py",
        "nested/keep.rs",
        "api/generated.go",
        "vendor/copied.py",
        "nested/drop.rs",
        "output.gen.css",
    ] {
        write(root, path, "value\n");
    }
    write(root, ".gitignore", "ignored.py\n");
    write(
        root,
        ".gitattributes",
        "api/generated.go linguist-generated\nvendor/** linguist-vendored\nnested/*.rs linguist-generated\n",
    );
    write(
        root,
        "nested/.gitattributes",
        "keep.rs -linguist-generated\n",
    );
    write(
        root,
        "model.go",
        "// Code generated by sqlc. DO NOT EDIT.\npackage model\n",
    );
    write(root, "data.json", "{\"url\": \"https://example.com\"}\n");
    write(root, "README.md", "# Project\n");
    git(root, &["add", "-f", "."]);
    // The result describes working-tree contents, not the staged blob.
    write(root, "src/main.rs", "fn main() {\n    run();\n}\n");
    write(root, "untracked.py", "untracked = 1\n");

    let options = AnalysisOptions {
        source_only: true,
        tracked_only: true,
        collect_individual_files: true,
        compute_complexity: false,
        ..AnalysisOptions::reproducible()
    };
    let analysis = Engine::new().analyze(root, &options).unwrap();
    assert_eq!(analysis.basic.total_files, 7);
    assert_eq!(analysis.basic.total_code_lines, 9);
    assert!(analysis.basic.is_consistent());
    let selected: Vec<_> = analysis
        .individual_files
        .iter()
        .map(|(path, _)| {
            Path::new(path)
                .strip_prefix(root.canonicalize().unwrap())
                .unwrap()
                .to_path_buf()
        })
        .collect();
    assert!(selected.contains(&".hooks/hook.py".into()));
    assert!(selected.contains(&"ignored.py".into()));
    assert!(selected.contains(&"packages/ui/widget.ts".into()));
    assert!(selected.contains(&"ci/pipeline/build/source.go".into()));
    assert!(selected.contains(&"ci/workbench/coverage/source.py".into()));
    assert!(selected.contains(&"nested/keep.rs".into()));
    assert!(!selected.contains(&"api/generated.go".into()));
    assert!(!selected.contains(&"vendor/copied.py".into()));
    assert!(!selected.contains(&"untracked.py".into()));
    assert_eq!(
        Engine::new().discover_files(root, &options).unwrap().len(),
        7
    );

    let filtered = Engine::new()
        .analyze(
            root,
            &AnalysisOptions {
                ignore_patterns: vec!["packages".into()],
                ..options.clone()
            },
        )
        .unwrap();
    assert_eq!(filtered.basic.total_files, 6);
    assert_eq!(filtered.basic.total_code_lines, 8);
}

#[test]
fn tracked_only_refuses_an_unversioned_directory() {
    let directory = tempfile::tempdir().unwrap();
    write(directory.path(), "source.py", "value = 1\n");
    let options = AnalysisOptions {
        tracked_only: true,
        ..AnalysisOptions::reproducible()
    };
    assert!(Engine::new().analyze(directory.path(), &options).is_err());
}

#[cfg(unix)]
#[test]
fn git_paths_preserve_newlines_and_do_not_follow_symlinks() {
    use std::os::unix::fs::symlink;
    let directory = tempfile::tempdir().unwrap();
    let root = directory.path();
    git(root, &["init", "-q"]);
    write(root, "source\nname.py", "value = 1\n");
    symlink("source\nname.py", root.join("alias.py")).unwrap();
    git(root, &["add", "."]);
    let options = AnalysisOptions {
        tracked_only: true,
        source_only: true,
        ..AnalysisOptions::reproducible()
    };
    let analysis = Engine::new().analyze(root, &options).unwrap();
    assert_eq!(analysis.basic.total_files, 1);
    assert_eq!(analysis.basic.total_code_lines, 1);
}
